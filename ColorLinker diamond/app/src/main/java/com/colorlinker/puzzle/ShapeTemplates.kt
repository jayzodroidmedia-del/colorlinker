    fun isCellValid(r: Int, c: Int, gridSize: Int, shapeType: Int): Boolean {
        if (shapeType == 0) return true
        val template = templates[shapeType] ?: return true
        
        val tempRows = template.size
        val tempCols = template[0].length
        
        val tempR = (r.toFloat() / gridSize * tempRows).toInt().coerceIn(0, tempRows - 1)
        val tempC = (c.toFloat() / gridSize * tempCols).toInt().coerceIn(0, tempCols - 1)
        
        return template[tempR][tempC] == '*'
    }
